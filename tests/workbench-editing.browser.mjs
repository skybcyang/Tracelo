import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { build } from 'esbuild';
import { chromium } from 'playwright';

const bundle = await build({ entryPoints: ['tests/helpers/card-fixture.mjs'], bundle: true, write: false, format: 'esm', external: ['electron', 'node:child_process'], alias: { obsidian: resolve('tests/helpers/obsidian-browser.mjs') } });
const browser = await chromium.launch({ headless: true });
const output = 'test-results/workbench-editing';
mkdirSync(output, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1728, height: 1080 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.route('https://tracelo.test/**', route => route.fulfill({ contentType: 'text/html', body: `<meta charset="utf-8"><style>${readFileSync('tests/helpers/obsidian-host.css', 'utf8')}\n${readFileSync('styles.css', 'utf8')}</style><script type="module">${bundle.outputFiles[0].text}</script>` }));
  await page.goto('https://tracelo.test/?workbench=1');
  await page.waitForFunction(() => window.cardFixture);
  const ids = await page.evaluate(() => window.cardFixture.ids);
  const choose = id => page.locator(`.wt-cover-flow [data-cover-task="${id}"]`).click();
  const stage = page.locator('.wt-task-stage');
  const composer = stage.locator('.wt-card-composer');
  const progress = stage.getByRole('textbox', { name: '记录当前进展', exact: true });
  await choose(ids.payment);
  await stage.locator('.wt-card-open').click();
  await page.waitForTimeout(350); // Legacy single-click handler waits 300 ms before toggling.
  assert.equal(await composer.count(), 0, 'stage title is reading content, never an edit toggle');
  await stage.locator('.wt-card-latest').click();
  await page.waitForTimeout(350);
  assert.equal(await composer.count(), 0, 'stage body never toggles editing');
  const before = { menus: await stage.locator('.wt-todo-more').count(), add: await stage.locator('.wt-add-todo').count() };
  await stage.getByRole('button', { name: '记录进展', exact: true }).click();
  const submit = composer.getByRole('button', { name: '记录进展', exact: true });
  const close = stage.getByRole('button', { name: '结束编辑', exact: true });
  const actionRow = await stage.evaluate(el => {
    const buttons = [...el.querySelectorAll('button')];
    const close = buttons.find(b => b.textContent.trim() === '结束编辑');
    const submit = el.querySelector('.wt-card-composer button[type=submit]');
    const a = close.getBoundingClientRect(), b = submit.getBoundingClientRect();
    return { sameParent: close.parentElement === submit.parentElement, centerDelta: Math.abs(a.y + a.height / 2 - b.y - b.height / 2) };
  });
  await page.screenshot({ path: `${output}/editing.png` });
  writeFileSync(`${output}/initial.json`, JSON.stringify({ at: new Date().toISOString(), before, actionRow }, null, 2));
  assert.deepEqual({ before, actionRow }, { before: { menus: 4, add: 1 }, actionRow: { sameParent: true, centerDelta: 0 } }, 'todo actions must be independent and progress buttons must share a row');

  await progress.fill('结束编辑后仍保留的进展草稿');
  await stage.locator('.wt-card-open').click();
  await page.waitForTimeout(350);
  assert.equal(await progress.inputValue(), '结束编辑后仍保留的进展草稿', 'stage title cannot close the editor');
  const addTodo = stage.getByRole('textbox', { name: '新增待办', exact: true });
  await addTodo.fill('待办输入不随进展关闭');
  await close.click();
  assert.equal(await composer.count(), 0);
  assert.equal(await stage.locator('.wt-todo-more').count(), 4);
  assert.equal(await addTodo.inputValue(), '待办输入不随进展关闭');
  await addTodo.fill('独立新增的下一步');
  await stage.locator('.wt-add-todo button[type=submit]').click();
  await stage.getByRole('checkbox', { name: '独立新增的下一步', exact: true }).waitFor();
  assert.equal(await composer.count(), 0, 'adding a todo never opens progress');
  await stage.getByRole('checkbox', { name: '独立新增的下一步', exact: true }).check();
  assert.equal(await composer.count(), 0, 'checking a todo never opens progress');
  await stage.getByRole('button', { name: '待办操作：独立新增的下一步', exact: true }).click();
  await page.getByRole('menuitem', { name: '编辑待办', exact: true }).click();
  await page.locator('.wt-prompt-modal input').fill('独立修改后的待办');
  await page.locator('.wt-prompt-modal').getByRole('button', { name: '确认', exact: true }).click();
  await stage.getByRole('checkbox', { name: '独立修改后的待办', exact: true }).waitFor();
  assert.equal(await composer.count(), 0, 'editing a todo never opens progress');
  await stage.getByRole('button', { name: '待办操作：独立修改后的待办', exact: true }).click();
  await page.getByRole('menuitem', { name: '删除待办', exact: true }).click();
  await stage.getByRole('checkbox', { name: '独立修改后的待办', exact: true }).waitFor({ state: 'detached' });
  assert.equal(await composer.count(), 0, 'removing a todo never opens progress');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await stage.getByRole('checkbox', { name: '独立修改后的待办', exact: true }).waitFor();
  await stage.getByRole('button', { name: '记录进展', exact: true }).click();
  assert.equal(await progress.inputValue(), '结束编辑后仍保留的进展草稿');
  const originalCount = await page.evaluate(() => window.cardFixture.plugin.tasks.find(t => t.id === window.cardFixture.ids.payment).events.filter(e => e.kind === 'progress').length);
  await page.evaluate(() => { const p = window.cardFixture.plugin; p.originalRecord = p.recordProgress; p.recordProgress = async () => { throw Error('isolated write failure'); }; });
  await submit.click();
  await page.getByText('isolated write failure', { exact: true }).waitFor();
  assert.equal(await progress.inputValue(), '结束编辑后仍保留的进展草稿');
  assert.equal(await close.isEnabled(), true);
  await page.evaluate(() => { const p = window.cardFixture.plugin; p.recordProgress = p.originalRecord; });
  await close.click();
  await choose(ids.plain);
  await stage.getByRole('button', { name: '记录进展', exact: true }).click();
  await stage.getByRole('button', { name: '添加待办', exact: true }).click();
  await addTodo.fill('空清单新增输入也保留');
  await close.click();
  assert.equal(await addTodo.inputValue(), '空清单新增输入也保留');
  await addTodo.fill('第一条独立待办');
  await stage.locator('.wt-add-todo button[type=submit]').click();
  await stage.getByRole('checkbox', { name: '第一条独立待办', exact: true }).waitFor();
  assert.equal(await composer.count(), 0, 'first todo also works independently');
  await choose(ids.payment);
  await stage.getByRole('button', { name: '记录进展', exact: true }).click();
  assert.equal(await progress.inputValue(), '结束编辑后仍保留的进展草稿');

  for (const [width, height, appearance] of [[1728,1080,'light'], [1280,720,'dark'], [800,650,'light'], [390,844,'dark']]) {
    await page.setViewportSize({ width, height });
    await page.evaluate(appearance => window.cardFixture.plugin.setAppearance('monochrome', appearance), appearance);
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => !document.querySelector('.work-timeline-view').getAnimations({ subtree: true }).some(a => a.playState === 'running' && a.effect?.getTiming().iterations !== Infinity));
    const a = await close.boundingBox(), b = await submit.boundingBox();
    assert.ok(a && b && Math.abs(a.y + a.height / 2 - b.y - b.height / 2) < 1, `same action row at ${width}`);
    assert.ok(await page.locator('.view-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1), `no horizontal overflow at ${width}`);
    await page.screenshot({ path: `${output}/${appearance}-${width}.png` });
  }
  await page.setViewportSize({ width: 1728, height: 1080 });
  await submit.click();
  await page.waitForFunction(id => !window.cardFixture.plugin.state.drafts[id], ids.payment);
  assert.equal(await composer.count(), 0);
  assert.equal(await page.evaluate(() => window.cardFixture.plugin.tasks.find(t => t.id === window.cardFixture.ids.payment).events.filter(e => e.kind === 'progress').length), originalCount + 1);
  assert.equal(await stage.locator('.wt-add-todo').count(), 1);
  assert.deepEqual(errors, []);
  console.log('PASS independent workbench todos, same-row progress actions, draft/failed-save recovery, task switching, narrow/dark rendering and successful save');
} finally { await browser.close(); }
